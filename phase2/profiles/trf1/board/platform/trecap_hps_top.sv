// TSH1 finite PCM HPS image. HPS pin declarations/mappings retain the inventoried board wrapper.
`default_nettype none
module trecap_hps_top(input wire CLOCK_50,
    output wire [14:0]                  HPS_DDR3_ADDR,
    output wire [2:0]                   HPS_DDR3_BA,
    output wire                         HPS_DDR3_CAS_N,
    output wire                         HPS_DDR3_CKE,
    output wire                         HPS_DDR3_CK_N,
    output wire                         HPS_DDR3_CK_P,
    output wire                         HPS_DDR3_CS_N,
    output wire [3:0]                   HPS_DDR3_DM,
    inout  wire [31:0]                  HPS_DDR3_DQ,
    inout  wire [3:0]                   HPS_DDR3_DQS_N,
    inout  wire [3:0]                   HPS_DDR3_DQS_P,
    output wire                         HPS_DDR3_ODT,
    output wire                         HPS_DDR3_RAS_N,
    output wire                         HPS_DDR3_RESET_N,
    input  wire                         HPS_DDR3_RZQ,
    output wire                         HPS_DDR3_WE_N,

    // HPS EMAC1, QSPI, SDIO, SPI, UART, USB, I2C, and GPIO pins selected by the frozen preset.
    output wire                         HPS_ENET_GTX_CLK,
    inout  wire                         HPS_ENET_INT_N,
    output wire                         HPS_ENET_MDC,
    inout  wire                         HPS_ENET_MDIO,
    input  wire                         HPS_ENET_RX_CLK,
    input  wire [3:0]                   HPS_ENET_RX_DATA,
    input  wire                         HPS_ENET_RX_DV,
    output wire [3:0]                   HPS_ENET_TX_DATA,
    output wire                         HPS_ENET_TX_EN,
    inout  wire [3:0]                   HPS_FLASH_DATA,
    output wire                         HPS_FLASH_DCLK,
    output wire                         HPS_FLASH_NCSO,
    inout  wire                         HPS_GSENSOR_INT,
    inout  wire                         HPS_I2C_CONTROL,
    inout  wire                         HPS_I2C1_SCLK,
    inout  wire                         HPS_I2C1_SDAT,
    inout  wire                         HPS_I2C2_SCLK,
    inout  wire                         HPS_I2C2_SDAT,
    inout  wire                         HPS_KEY,
    inout  wire                         HPS_LED,
    inout  wire                         HPS_LTC_GPIO,
    output wire                         HPS_SD_CLK,
    inout  wire                         HPS_SD_CMD,
    inout  wire [3:0]                   HPS_SD_DATA,
    output wire                         HPS_SPIM_CLK,
    input  wire                         HPS_SPIM_MISO,
    output wire                         HPS_SPIM_MOSI,
    output wire                         HPS_SPIM_SS,
    input  wire                         HPS_UART_RX,
    output wire                         HPS_UART_TX,
    inout  wire                         HPS_CONV_USB_N,
    input  wire                         HPS_USB_CLKOUT,
    inout  wire [7:0]                   HPS_USB_DATA,
    input  wire                         HPS_USB_DIR,
    input  wire                         HPS_USB_NXT,
    output wire                         HPS_USB_STP,

    output wire [9:0] LEDR);
    wire h2f_reset_n;
    // Only the HPS reset resets this bus: KEY cannot cancel an AXI response.
    wire async_reset_n=h2f_reset_n;
    (* async_reg="true" *) reg [2:0] reset_release=3'b0;
    always @(posedge CLOCK_50 or negedge async_reset_n)
        if(!async_reset_n) reset_release<=0;
        else reset_release<={reset_release[1:0],1'b1};
    wire reset_n=reset_release[2];
    wire [20:0] address;wire read_req,write_req,burst,wait_req,read_valid,write_valid;
    wire [31:0] write_data,read_data;wire [3:0] byteenable;wire [1:0] response;
    platform_designer_wrapper platform(
        .clk_50_i(CLOCK_50),.bridge_reset_n_i(reset_n),.h2f_reset_n_o(h2f_reset_n),
        .HPS_DDR3_ADDR(HPS_DDR3_ADDR),
        .HPS_DDR3_BA(HPS_DDR3_BA),
        .HPS_DDR3_CAS_N(HPS_DDR3_CAS_N),
        .HPS_DDR3_CKE(HPS_DDR3_CKE),
        .HPS_DDR3_CK_N(HPS_DDR3_CK_N),
        .HPS_DDR3_CK_P(HPS_DDR3_CK_P),
        .HPS_DDR3_CS_N(HPS_DDR3_CS_N),
        .HPS_DDR3_DM(HPS_DDR3_DM),
        .HPS_DDR3_DQ(HPS_DDR3_DQ),
        .HPS_DDR3_DQS_N(HPS_DDR3_DQS_N),
        .HPS_DDR3_DQS_P(HPS_DDR3_DQS_P),
        .HPS_DDR3_ODT(HPS_DDR3_ODT),
        .HPS_DDR3_RAS_N(HPS_DDR3_RAS_N),
        .HPS_DDR3_RESET_N(HPS_DDR3_RESET_N),
        .HPS_DDR3_RZQ(HPS_DDR3_RZQ),
        .HPS_DDR3_WE_N(HPS_DDR3_WE_N),
        .HPS_ENET_GTX_CLK(HPS_ENET_GTX_CLK),
        .HPS_ENET_INT_N(HPS_ENET_INT_N),
        .HPS_ENET_MDC(HPS_ENET_MDC),
        .HPS_ENET_MDIO(HPS_ENET_MDIO),
        .HPS_ENET_RX_CLK(HPS_ENET_RX_CLK),
        .HPS_ENET_RX_DATA(HPS_ENET_RX_DATA),
        .HPS_ENET_RX_DV(HPS_ENET_RX_DV),
        .HPS_ENET_TX_DATA(HPS_ENET_TX_DATA),
        .HPS_ENET_TX_EN(HPS_ENET_TX_EN),
        .HPS_FLASH_DATA(HPS_FLASH_DATA),
        .HPS_FLASH_DCLK(HPS_FLASH_DCLK),
        .HPS_FLASH_NCSO(HPS_FLASH_NCSO),
        .HPS_GSENSOR_INT(HPS_GSENSOR_INT),
        .HPS_I2C_CONTROL(HPS_I2C_CONTROL),
        .HPS_I2C1_SCLK(HPS_I2C1_SCLK),
        .HPS_I2C1_SDAT(HPS_I2C1_SDAT),
        .HPS_I2C2_SCLK(HPS_I2C2_SCLK),
        .HPS_I2C2_SDAT(HPS_I2C2_SDAT),
        .HPS_KEY(HPS_KEY),
        .HPS_LED(HPS_LED),
        .HPS_LTC_GPIO(HPS_LTC_GPIO),
        .HPS_SD_CLK(HPS_SD_CLK),
        .HPS_SD_CMD(HPS_SD_CMD),
        .HPS_SD_DATA(HPS_SD_DATA),
        .HPS_SPIM_CLK(HPS_SPIM_CLK),
        .HPS_SPIM_MISO(HPS_SPIM_MISO),
        .HPS_SPIM_MOSI(HPS_SPIM_MOSI),
        .HPS_SPIM_SS(HPS_SPIM_SS),
        .HPS_UART_RX(HPS_UART_RX),
        .HPS_UART_TX(HPS_UART_TX),
        .HPS_CONV_USB_N(HPS_CONV_USB_N),
        .HPS_USB_CLKOUT(HPS_USB_CLKOUT),
        .HPS_USB_DATA(HPS_USB_DATA),
        .HPS_USB_DIR(HPS_USB_DIR),
        .HPS_USB_NXT(HPS_USB_NXT),
        .HPS_USB_STP(HPS_USB_STP),
        .csr_avs_address_o(address),.csr_avs_read_o(read_req),.csr_avs_write_o(write_req),
        .csr_avs_writedata_o(write_data),.csr_avs_byteenable_o(byteenable),.csr_avs_burstcount_o(burst),
        .csr_avs_waitrequest_i(wait_req),.csr_avs_readdata_i(read_data),.csr_avs_readdatavalid_i(read_valid),
        .csr_avs_writeresponsevalid_i(write_valid),.csr_avs_response_i(response),
        .avm_address_i(64'd0),.avm_write_i(1'b0),.avm_writedata_i(64'd0),
        .avm_byteenable_i(8'd0),.avm_burstcount_i(1'b1),
        .avm_waitrequest_o(),.avm_writeresponsevalid_o(),.avm_response_o());
    trecap_rf_board_adapter #(.SOURCE_ID(`TSH_SOURCE_ID)) adapter(
        .clk(CLOCK_50),.rst_n(reset_n),.avs_address(address),.avs_read(read_req),.avs_write(write_req),
        .avs_writedata(write_data),.avs_byteenable(byteenable),.avs_burstcount(burst),
        .avs_waitrequest(wait_req),.avs_readdata(read_data),.avs_readdatavalid(read_valid),
        .avs_writeresponsevalid(write_valid),.avs_response(response));
    assign LEDR=10'd0;
endmodule
`default_nettype wire
