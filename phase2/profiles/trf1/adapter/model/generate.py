"""Rebuild coefficient ROM, independent fixtures and numerical evidence."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np
from scipy.signal import resample_poly
import scipy

from reference import coefficients, prototype, convert, float_reference, round_away

BASE = Path(__file__).resolve().parents[1]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def hexfile(path, values, width):
    mask = (1 << (width * 4)) - 1
    path.write_text("".join(f"{int(v) & mask:0{width}x}\n" for v in values), encoding="ascii")


def adversarial(coeff, phase, polarity):
    # At causal output group20, history[lag] is input[20-lag].
    # Match every selected coefficient's sign to attain its L1 bound.
    pair = np.full((21, 2), 128, dtype=np.uint8)
    lane = phase % 2
    mixer_sign = -1 if phase in (1, 2) else 1
    for lag in range(21):
        index = 4 * lag + phase
        c = int(coeff[index]) if index < 81 else 0
        pair[20-lag, lane] = 255 if c * mixer_sign * polarity >= 0 else 0
    return pair


def main():
    for p in (BASE / "coefficients", BASE / "vectors"):
        p.mkdir(parents=True, exist_ok=True)
    taps = coefficients()
    assert np.max(taps) < (1 << 17) and np.min(taps) >= -(1 << 17)
    assert np.array_equal(taps, taps[::-1])
    code = ["// Generated by model/generate.py. Signed18 coefficients with16 fractional bits.",
            "function automatic signed [17:0] rf_coeff(input logic [6:0] index);",
            "    case (index)"]
    for index, c in enumerate(taps):
        literal = ("-" if c < 0 else "") + f"18'sd{abs(int(c))}"
        code.append(f"        7'd{index}: rf_coeff = {literal};")
    code += ["        default: rf_coeff = 18'sd0;", "    endcase", "endfunction", ""]
    (BASE / "coefficients/rf_coefficients.svh").write_text("\n".join(code), encoding="ascii")
    hexfile(BASE / "coefficients/rf_coefficients.hex", taps, 5)
    (BASE / "coefficients/coefficients.json").write_text(json.dumps({
        "design": "4 * firwin(81, 0.25, window=('kaiser', 8.6))",
        "fractional_bits": 16, "coefficient_bits": 18,
        "quantization": "nearest ties to even", "integers": taps.tolist(),
        "phase_sums": [int(sum(taps[p::4])) for p in range(4)],
        "phase_l1": [int(sum(abs(taps[p::4]))) for p in range(4)],
        "numpy": np.__version__, "scipy": scipy.__version__}, indent=2) + "\n")

    rng = np.random.default_rng(20261103)
    cases = []
    def add(name, pairs, gain=2, **metadata):
        cases.append((name, np.asarray(pairs, dtype=np.uint8), gain, metadata))

    add("single_min", [[0, 0]])
    add("single_max", [[255, 255]])
    add("single_mid", [[127, 128]])
    for n in (2, 3, 9, 10, 11):
        add(f"short_{n}", rng.integers(0, 256, (n, 2), dtype=np.uint8))
    for value in (0, 127, 128, 255):
        add(f"dc_{value}", np.full((96, 2), value))
    for lane in (0, 1):
        for where in (0, 32, 63):
            p = np.full((64, 2), 128, dtype=np.uint8)
            p[where, lane] = 255
            add(f"impulse_{'i' if lane == 0 else 'q'}_{where}", p)
    n = np.arange(128)
    for sign in (-1, 1):
        z = np.exp(2j * np.pi * sign * 13 * n / 128)
        p = np.rint(127.5 + 100 * np.stack([z.real, z.imag], axis=1)).astype(np.uint8)
        add(f"tone_{'negative' if sign < 0 else 'positive'}", p)
    for gain in range(4):
        add(f"random_g{gain}", rng.integers(0, 256, (257, 2), dtype=np.uint8), gain)
        add(f"extremes_g{gain}", 255 * rng.integers(0, 2, (127, 2), dtype=np.uint8), gain)
    for phase in range(4):
        for polarity in (-1, 1):
            add(f"l1_p{phase}_{'neg' if polarity < 0 else 'pos'}", adversarial(taps, phase, polarity))
    # Public regression uses generated signals only.

    manifests = []
    for name, pairs, gain, metadata in cases:
        result = convert(pairs, gain)
        pathbase = BASE / "vectors" / name
        inputs = pathbase.with_suffix(".input.hex")
        outputs = pathbase.with_suffix(".output.hex")
        clips = pathbase.with_suffix(".clip.hex")
        hexfile(inputs, pairs[:, 0].astype(np.int64) | (pairs[:, 1].astype(np.int64) << 8), 4)
        hexfile(outputs, result["samples"], 3)
        hexfile(clips, result["clipped"], 1)
        ideal = float_reference(pairs, gain)
        # Compare before integer rounding so coefficient quantization is isolated.
        fir_error = result["accumulators"] / float(1 << (16-gain)) - ideal
        step = 1 << (16-gain)
        ties = (abs(result["accumulators"]) % step) == step // 2
        manifests.append(dict(name=name, pair_count=len(pairs), gain_shift=gain,
            expected_clip_count=int(result["clipped"].sum()),
            positive_rounding_ties=int(np.sum(ties & (result["accumulators"] > 0))),
            negative_rounding_ties=int(np.sum(ties & (result["accumulators"] < 0))),
            input_hex=str(inputs.relative_to(BASE)).replace("\\", "/"),
            output_hex=str(outputs.relative_to(BASE)).replace("\\", "/"),
            clip_hex=str(clips.relative_to(BASE)).replace("\\", "/"),
            input_sha256=sha(inputs), output_sha256=sha(outputs), clip_sha256=sha(clips),
            coeff_only_max_abs_error_counts=float(np.max(abs(fir_error))), **metadata))
    (BASE / "vectors/manifest.json").write_text(json.dumps({"schema": "rf-adapter-vectors-v1",
        "reference": "Independent full integer convolution, crop40, quadrant mixer, round and saturate",
        "cases": manifests}, indent=2) + "\n")
    (BASE / "vectors/cases.txt").write_text("".join(
        f"{r['name']} {r['pair_count']} {r['gain_shift']} {r['expected_clip_count']}\n" for r in manifests), encoding="ascii")

    # Independent numerical qualification of alignment against SciPy's centered API.
    worst_alignment = 0.0
    for count in (1, 2, 3, 9, 10, 11, 41, 257):
        z = rng.normal(size=count) + 1j * rng.normal(size=count)
        inserted = np.zeros(count*4, dtype=np.complex128)
        inserted[::4] = z
        causal = np.convolve(inserted, prototype())[40:40+count*4]
        scipy_out = resample_poly(z, 4, 1, window=("kaiser", 8.6), padtype="constant")
        error = float(np.max(np.abs(causal-scipy_out)))
        assert error < 2e-14
        worst_alignment = max(worst_alignment, error)
    rounding_checks = 0
    for shift in (13, 14, 15, 16):
        half = 1 << (shift - 1)
        values = np.array([-3*half-1, -3*half, -3*half+1, -half-1, -half, -half+1,
                            0, half-1, half, half+1, 3*half-1, 3*half, 3*half+1])
        expected = np.array([-2, -2, -1, -1, -1, 0, 0, 0, 1, 1, 1, 2, 2])
        assert np.array_equal(round_away(values, shift), expected)
        rounding_checks += len(values)
    bounds = [255 * int(sum(abs(taps[p::4]))) for p in range(4)]
    assert max(bounds) < (1 << 26)
    assert max(bounds) / (1 << 15) + 0.5 < 2047
    adversarial_results = [r for r in manifests if r["name"].startswith("l1_")]
    assert sum(r["expected_clip_count"] for r in adversarial_results) > 0
    validation = dict(status="PASS", golden_method="Full convolution independent of RTL schedule",
        numerical_only=True, rtl_simulation_performed=False, hardware_used=False,
        cases=len(manifests), total_pairs=sum(r["pair_count"] for r in manifests),
        total_samples=sum(4*r["pair_count"] for r in manifests),
        fixture_positive_rounding_ties=sum(r["positive_rounding_ties"] for r in manifests),
        fixture_negative_rounding_ties=sum(r["negative_rounding_ties"] for r in manifests),
        rounding_boundary_checks=rounding_checks,
        floating_alignment_max_abs_error=worst_alignment,
        accumulator_abs_bounds_by_phase=bounds,
        gain1_guaranteed_no_clipping_for_any_CU8=True,
        gain2_can_clip_adversarial_input=True,
        coeff_only_max_abs_error_counts=max(r["coeff_only_max_abs_error_counts"] for r in manifests),
        files={str(p.relative_to(BASE)).replace("\\", "/"): sha(p)
               for p in [BASE / "model/reference.py", BASE / "model/generate.py",
                         BASE / "coefficients/rf_coefficients.svh", BASE / "vectors/manifest.json"]})
    (BASE / "model/validation.json").write_text(json.dumps(validation, indent=2) + "\n")
    print(json.dumps({k:v for k,v in validation.items() if k != "files"}, indent=2))


if __name__ == "__main__":
    main()
